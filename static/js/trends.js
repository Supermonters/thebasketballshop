let gmCurrent = null;
let gmIdx = 0;

const gmBackdrop  = gmOverlay.querySelector('.gm-backdrop');
const gmClose     = gmOverlay.querySelector('.gm-close');
const gmMainImg   = gmOverlay.querySelector('.gm-main-img');
const gmPrev      = gmOverlay.querySelector('.gm-prev');
const gmNext      = gmOverlay.querySelector('.gm-next');
const gmThumbs    = gmOverlay.querySelector('.gm-thumbs');
const gmName      = gmOverlay.querySelector('.gm-name');
const gmShoeLine  = gmOverlay.querySelector('.gm-shoe-line');
const gmHeadshot  = gmOverlay.querySelector('.gm-headshot');
const gmRankBadge = gmOverlay.querySelector('.gm-rank-badge');
const gmCounter   = gmOverlay.querySelector('.gm-counter');
const gmShoeName  = gmOverlay.querySelector('.gm-shoe-name');

function openGallery(player) {
  gmCurrent = player;
  gmIdx = 0;

  const brandColor = BRAND_COLORS[player.brand] || '#fd5927';
  gmName.textContent = `${player.name}`;
  gmShoeLine.innerHTML = player.freeAgent
    ? `<span class="free-agent-tag">SHOE FREE AGENT</span> ${player.shoe}`
    : `<span style="color:${brandColor};font-weight:700">${player.brand}</span>&nbsp;${player.shoe}`;
  gmHeadshot.src = `https://cdn.nba.com/headshots/nba/latest/260x190/${player.id}.png`;
  gmRankBadge.textContent = `#${player.rank} Trending`;

  gmThumbs.innerHTML = player.shoeImgs.map((src, i) =>
    `<img src="${src}" class="gm-thumb${i === 0 ? ' active' : ''}" data-idx="${i}"
          alt="colorway ${i + 1}" onerror="this.style.display='none'">`
  ).join('');

  setGMImg(0, true);
  gmOverlay.classList.add('open');
  document.body.style.overflow = 'hidden';
}

function closeGallery() {
  gmOverlay.classList.remove('open');
  document.body.style.overflow = '';
}

function setGMImg(idx, instant) {
  if (!gmCurrent) return;
  const len = gmCurrent.shoeImgs.length;
  gmIdx = ((idx % len) + len) % len;

  if (instant) {
    gmMainImg.src = gmCurrent.shoeImgs[gmIdx];
  } else {
    gmMainImg.style.opacity = '0';
    gmMainImg.style.transform = 'scale(0.97)';
    setTimeout(() => {
      gmMainImg.src = gmCurrent.shoeImgs[gmIdx];
      gmMainImg.style.opacity = '1';
      gmMainImg.style.transform = 'scale(1)';
    }, 130);
  }

  gmCounter.textContent = `${gmIdx + 1} / ${len}`;
  gmShoeName.textContent = extractShoeName(gmCurrent.shoeImgs[gmIdx]) || gmCurrent.shoe;

  gmThumbs.querySelectorAll('.gm-thumb').forEach((t, i) => {
    t.classList.toggle('active', i === gmIdx);
    if (i === gmIdx) t.scrollIntoView({ inline: 'nearest', behavior: 'smooth' });
  });
}

gmClose.addEventListener('click', closeGallery);
gmBackdrop.addEventListener('click', closeGallery);
gmPrev.addEventListener('click', () => setGMImg(gmIdx - 1));
gmNext.addEventListener('click', () => setGMImg(gmIdx + 1));
gmThumbs.addEventListener('click', e => {
  const t = e.target.closest('.gm-thumb');
  if (t) setGMImg(parseInt(t.dataset.idx));
});

document.addEventListener('keydown', e => {
  if (!gmOverlay.classList.contains('open')) return;
  if (e.key === 'Escape')      closeGallery();
  if (e.key === 'ArrowLeft')   setGMImg(gmIdx - 1);
  if (e.key === 'ArrowRight')  setGMImg(gmIdx + 1);
});

